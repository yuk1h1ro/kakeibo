// ============================================================
// 固定費の合計 (機能122) と 定期支出の自動検出・登録提案 (機能081)
//
// 122 は「繰り返し入力(recurring_rules)に登録済みのもの」だけを集計する。
//     推測ではなく登録内容そのものなので、数字を断定して出せる。
// 081 は過去の記録からの**推測**。誤検出で登録が勝手に増えるのが最悪なので、
//     - ここでは候補を出すだけで、登録は必ず画面側のユーザー操作を経る
//     - すでに登録済み(停止中も含む)の店は候補から外す
//     - 「いらない」と言われた候補は端末に覚えて二度と出さない
//     という三段構えにしてある。
// ============================================================

