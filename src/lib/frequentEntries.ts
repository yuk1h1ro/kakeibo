// ============================================================
// よく使う記録 (入力タブの1タップ入力)
//
// 「電車 羽沢横浜国大→新宿 ¥〇〇」のように、同じ内容・同じ金額で何度も
// 記録しているものを、過去の記録から拾って候補にする。(純粋関数)
//
// 「最近の記録から入力」(直近5件)とは別に持つのは、そちらは新しい順なので、
// 毎日のように使う定番でも、他の記録を何件か入れると押し出されて消えるため。
// こちらは「何回使ったか」で並べるので、定番ほど残る。
//
// 同じ内容とみなすのは カテゴリ・お店・メモ・金額・彼女の負担分 がすべて同じとき。
// どれか1つでも違えば別の候補にする — 1タップで入るのはこの5つなので、
// まとめてしまうと「押したのに金額が違う」が起きる。
// ============================================================

import { normalizeStoreName } from './storeCategories'
import { isSplitPart } from './splits'
import { favorOf } from './favors'
import { addDays } from './reportBuckets'
import { isAutoGenerated, type Transaction } from './types'

/** 何回記録したら候補にするか。1回きりの買い物は定番ではない */
export const FREQUENT_MIN_COUNT = 2

/** 何日前までの記録を数えるか。運賃や値段が変わったあとの古い金額を出さないため */
export const FREQUENT_WINDOW_DAYS = 180

/**
 * 候補の数。入力欄の真上に出すので、多いと入力欄(カテゴリ)が画面の下へ
 * 押し出される。390px 幅の画面で、4件までならカテゴリの段が見えたまま残る
 */
export const FREQUENT_LIMIT = 4

export interface FrequentEntry {
  /** 突き合わせのキー(React の key にも使う) */
  key: string
  category: string | null
  /** 表示と入力に使う店名・メモ。いちばん最近の記録の書き方を採る */
  store: string
  memo: string
  amount: number
  partnerAmount: number
  /** 期間内に記録した回数 */
  count: number
  /** いちばん最近の日付 (YYYY-MM-DD) */
  lastDate: string
}

/** カテゴリ・お店・メモ・金額・彼女の負担分 を1つのキーにする */
export function entryKey(e: {
  category: string | null
  store: string
  memo: string
  amount: number
  partnerAmount: number
}): string {
  return [e.category ?? '', normalizeStoreName(e.store), e.memo.trim(), e.amount, e.partnerAmount].join('|')
}

/**
 * よく使う記録を、使った回数の多い順に返す。同じ回数なら最近使ったほうを先に。(純粋関数)
 *
 * 数えないもの:
 *   - 支出以外(預かり・返金・調整)… 入力タブで入れるものではない
 *   - 繰り返し入力が作った行 … 何もしなくても毎月入る
 *   - 分割の内訳 … 1件だけ入れ直しても会計にならない
 *   - おごり・値引きの付いた記録 … 1タップでは「誰にいくら」までは入らないので、
 *     支払った額だけが入ると、本来の値段が分からない記録になる
 *
 * exclude に渡したもの(テンプレートなど)と同じ内容は出さない — 同じ候補が2か所に並ぶため。
 */
export function frequentEntries(
  transactions: readonly Transaction[],
  today: string,
  exclude: ReadonlySet<string> = new Set()
): FrequentEntry[] {
  const since = addDays(today, -FREQUENT_WINDOW_DAYS)
  const byKey = new Map<string, FrequentEntry>()
  for (const t of transactions) {
    if (t.type !== 'expense') continue
    if (t.date < since || t.date > today) continue
    if (isAutoGenerated(t) || isSplitPart(t) || favorOf(t) !== null) continue
    if (!Number.isInteger(t.amount) || t.amount <= 0) continue
    const partnerAmount = t.partner_amount > 0 ? t.partner_amount : 0
    const store = (t.store ?? '').trim()
    const memo = (t.memo ?? '').trim()
    const key = entryKey({ category: t.category, store, memo, amount: t.amount, partnerAmount })
    if (exclude.has(key)) continue
    const prev = byKey.get(key)
    if (!prev) {
      byKey.set(key, {
        key,
        category: t.category,
        store,
        memo,
        amount: t.amount,
        partnerAmount,
        count: 1,
        lastDate: t.date,
      })
      continue
    }
    prev.count++
    if (t.date > prev.lastDate) {
      // 表記はいちばん最近の記録に合わせる(「羽沢横浜国大」と「羽沢」の揺れ)
      prev.lastDate = t.date
      prev.store = store
      prev.memo = memo
    }
  }
  return [...byKey.values()]
    .filter((e) => e.count >= FREQUENT_MIN_COUNT)
    .sort((a, b) => b.count - a.count || b.lastDate.localeCompare(a.lastDate) || a.key.localeCompare(b.key))
    .slice(0, FREQUENT_LIMIT)
}

/**
 * 候補に出す名前。お店とメモの両方があれば両方を出す。(純粋関数)
 * 電車では「JR」「羽沢横浜国大→新宿」のように、どちらか片方だけでは
 * 区間が分からないことが多い。どちらも無ければカテゴリ名
 */
export function frequentLabel(e: FrequentEntry, labelOf: (category: string | null) => string): string {
  const parts = [e.store, e.memo].filter((s) => s !== '')
  return parts.length > 0 ? parts.join(' ') : labelOf(e.category)
}
